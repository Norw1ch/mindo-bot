let lang = LANGS[savedLang()] ? savedLang() : 'ru';

function t(text, ...args) {
  const row = lang === 'ru' ? null : TEXTS[text];
  const out = row ? row[lang === 'uk' ? 0 : 1] : text;
  return args.length ? out.replace(/\{(\d)\}/g, (m, i) => args[i]) : out;
}

// Все написания текста: на русском и в переводах
function allSpellings(text) {
  return [text, ...(TEXTS[text] || [])];
}

// Как писать даты и числа на выбранном языке
function locale() {
  return LANGS[lang].locale;
}

// Тексты, которые лежат прямо в странице: <button data-t="Отмена">
function translatePage() {
  document.documentElement.lang = lang;
  document.title = t('Мои задачи');
  document.querySelectorAll('[data-t]').forEach((el) => { el.textContent = t(el.dataset.t); });
}

function setLang(code) {
  lang = code;
  try {
    localStorage.setItem(LS_PREFIX + LANG_KEY, code);
  } catch { /* не страшно: язык всё равно придёт из облака */ }
  translatePage();
}

// Первым среди модулей: остальным при загрузке уже нужен язык
modules.lang = {
  load(raw) {
    if (LANGS[raw[LANG_KEY]] && raw[LANG_KEY] !== lang) setLang(raw[LANG_KEY]);
  },
};

translatePage();
